def generate_en_th_json():
    dict_path = os.path.join(os.path.dirname(__file__), "cefr_dictionary.json")
    out_path = os.path.join(os.path.dirname(__file__), "en_th.json")

    if not os.path.exists(dict_path):
        print(f"Error: {dict_path} not found.")
        return

    existing = {}
    if os.path.exists(out_path):
        try:
            with open(out_path, "r", encoding="utf-8") as f:
                existing = json.load(f)
        except Exception:
            existing = {}

    with open(dict_path, "r", encoding="utf-8") as f:
        cefr_data = json.load(f)

    result = {}
    missing_count = 0

    for level, words in cefr_data.items():
        for entry in words:
            word = entry["word"].upper()
            meaning_en = entry.get("meaning", f"English word ({word.lower()})")
            if meaning_en.startswith("CEFR"):
                meaning_en = f"English word ({word.lower()})"

            if word in VOCAB_MAPPING:
                result[word] = VOCAB_MAPPING[word]
            elif word in existing and existing[word].get("th"):
                result[word] = existing[word]
            else:
                missing_count += 1
                result[word] = {
                    "en": meaning_en,
                    "th": f"คำศัพท์ ({word.lower()})"
                }

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2, ensure_ascii=False)

    print(f"Successfully generated {out_path} with {len(result)} total entries!")
    print(f"Direct mapped: {len(VOCAB_MAPPING)} words. Retained/Fallback: {missing_count} words.")

if __name__ == "__main__":
    generate_en_th_json()
