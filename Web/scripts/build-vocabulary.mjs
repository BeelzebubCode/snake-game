import { readFile, mkdir, writeFile } from 'node:fs/promises';
const source = new URL('../data-source/', import.meta.url);
const levels = JSON.parse(await readFile(new URL('cefr_dictionary.json', source), 'utf8'));
const glosses = JSON.parse(await readFile(new URL('en_th.json', source), 'utf8'));
const entries = new Map();
let skipped = 0;
for (const [level, words] of Object.entries(levels)) {
  for (const entry of words) {
    const word = entry.word.trim().toUpperCase(),
      meaningTh = glosses[word]?.th?.trim();
    if (!/^[A-Z]{2,24}$/.test(word) || !meaningTh) {
      skipped++;
      continue;
    }
    entries.set(word, { word, meaningTh, level });
  }
}
const output = new URL('../public/data/', import.meta.url);
await mkdir(output, { recursive: true });
await writeFile(new URL('vocabulary.json', output), JSON.stringify([...entries.values()]));
await writeFile(
  new URL('README.md', output),
  '# Legacy vocabulary\n\nGenerated by node scripts/build-vocabulary.mjs from data-source/cefr_dictionary.json and data-source/en_th.json (Python archive: python-v1-archive). ' +
    entries.size +
    ' entries; ' +
    skipped +
    ' entries excluded by the spelling/translation filter.\n\nLevel labels and translations are inherited from V1 and have not all been reviewed. Some original scripts assign levels by word length. Do not describe this collection as independently verified CEFR data. Review original data sources and distribution permissions before a public release.\n',
);
console.log('Prepared ' + entries.size + ' legacy vocabulary entries; skipped ' + skipped + '.');
